def seed_extended_faq(apps, schema_editor) -> None:
    FaqItem = apps.get_model("supportchat", "FaqItem")
    for question, short, answer, order, in_chat, on_home in FAQ_ITEMS:
        item = FaqItem.objects.filter(question=question).order_by("id").first()
        if item is None:
            FaqItem.objects.create(
                question=question,
                question_short=short,
                answer=answer,
                order=order,
                is_active=True,
                show_in_chat=in_chat,
                show_on_home=on_home,
            )
            continue
        update_fields: list[str] = []
        if not (item.answer or "").strip():
            item.answer = answer
            update_fields.append("answer")
        if not (item.question_short or "").strip():
            item.question_short = short
            update_fields.append("question_short")
        if update_fields:
            item.is_active = True
            update_fields.append("is_active")
            item.save(update_fields=update_fields)


def unseed_extended_faq(apps, schema_editor) -> None:
    FaqItem = apps.get_model("supportchat", "FaqItem")
    for question, _short, answer, _order, _in_chat, _on_home in FAQ_ITEMS:
        FaqItem.objects.filter(question=question, answer=answer).delete()


