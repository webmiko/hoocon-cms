def empty_state_help_for(model_admin: object) -> str:
    """Текст пустого списка: свой атрибут админки или общий справочник.

    Args:
        model_admin: Экземпляр ModelAdmin из changelist.

    Returns:
        Пояснение раздела или пустая строка, если текста нет.
    """
    own = getattr(model_admin, "empty_state_help", "") or ""
    if isinstance(own, str) and own.strip():
        return own.strip()
    model = getattr(model_admin, "model", None)
    if model is None:
        return ""
    return EMPTY_STATE_HELP.get(model._meta.label, "")
